#!/usr/bin/env node
/* eslint-disable no-console */

/**
 * Refreshes src/data/publications.js from the public Hashnode profile page.
 *
 * Hashnode put its GraphQL API behind a paid plan in May 2026, and the blog's
 * own RSS feed sits behind a bot check, so neither is usable here. The
 * hashnode.com profile page is still plain HTML with the post list embedded in
 * the Next.js payload, which is what this reads.
 *
 * Existing entries keep their hand-written `brief` and `publisher`: only new
 * posts are added, and titles, dates, covers and read times are refreshed.
 * Review the diff before committing.
 *
 * Usage: npm run fetch:publications
 */

const fs = require('fs');
const path = require('path');

const USERNAME = 'ahammadshawki8';
const PROFILE = `https://hashnode.com/@${USERNAME}`;
const OUT = path.join(__dirname, '..', 'src', 'data', 'publications.js');

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 '
  + '(KHTML, like Gecko) Chrome/125.0 Safari/537.36';

/** Pull the balanced JSON array that follows `"initialPosts":`. */
const extractInitialPosts = (payload) => {
  const key = '"initialPosts":';
  const at = payload.indexOf(key);
  if (at === -1) throw new Error('initialPosts not found; the profile page layout changed.');

  const start = payload.indexOf('[', at);
  let depth = 0;
  for (let i = start; i < payload.length; i += 1) {
    if (payload[i] === '[') depth += 1;
    else if (payload[i] === ']') {
      depth -= 1;
      if (depth === 0) return payload.slice(start, i + 1);
    }
  }
  throw new Error('Unbalanced initialPosts array.');
};

/**
 * House style: no en or em dashes anywhere on the site. Hashnode titles carry
 * them, so they are rewritten to a comma here rather than fixed by hand later.
 */
const normalise = (s) => String(s)
  .replace(/\s*[–—―]\s*/g, ', ')
  // A dash that became a comma leaves a title-cased conjunction behind it.
  .replace(/, (And|Or|But|Then) /g, (_, w) => `, ${w.toLowerCase()} `)
  .replace(/[‘’]/g, "'")
  .replace(/[“”]/g, '"')
  .replace(/\s+/g, ' ')
  .trim();

const escape = (s) => String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");

const render = (posts) => {
  const entries = posts.map((p) => {
    const lines = [
      '  {',
      `    title: '${escape(p.title)}',`,
      `    url: '${escape(p.url)}',`,
      `    date: '${p.date}',`,
      `    readTime: ${p.readTime},`,
    ];
    if (p.cover) lines.push(`    cover: '${escape(p.cover)}',`);
    if (p.publisher) lines.push(`    publisher: '${escape(p.publisher)}',`);
    lines.push('    brief:');
    lines.push(`      '${escape(p.brief)}',`);
    lines.push('  },');
    return lines.join('\n');
  }).join('\n');

  return `/**
 * Posts from https://${USERNAME}.hashnode.dev.
 *
 * Generated by \`npm run fetch:publications\`. Hand-written \`brief\` and
 * \`publisher\` values are preserved across regeneration, so edit them freely.
 *
 * @typedef {Object} Post
 * @property {string} title
 * @property {string} url - Canonical post URL, opened in a new tab
 * @property {string} date - YYYY-MM-DD
 * @property {number} readTime - Minutes
 * @property {string|undefined} cover - Absolute image URL
 * @property {string} brief - Opening lines of the post
 * @property {string|undefined} publisher - Where it first appeared, if not Hashnode
 */
const publications = [
${entries}
];

export default publications;
`;
};

const main = async () => {
  console.log(`Fetching ${PROFILE}`);
  const res = await fetch(PROFILE, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`Profile fetch failed: HTTP ${res.status}`);

  const html = await res.text();
  const payload = html.replace(/\\"/g, '"').replace(/\\\\/g, '\\');
  const raw = extractInitialPosts(payload).replace(/\$D/g, '');
  const fetched = JSON.parse(raw);

  const existing = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  // Split into one block per entry first. Matching brief/publisher across the
  // whole file lets a greedy match cross entry boundaries and mis-assign them.
  const keptBrief = new Map();
  const keptPublisher = new Map();
  existing.split(/\n\s*\},?\s*\n/).forEach((block) => {
    const url = /url:\s*'([^']+)'/.exec(block);
    if (!url) return;

    // `brief:` may be a single string or several concatenated with `+`.
    const brief = /brief:\s*\r?\n?\s*((?:'(?:[^'\\]|\\.)*'\s*\+?\s*\r?\n?\s*)+)/.exec(block);
    if (brief) {
      const joined = (brief[1].match(/'(?:[^'\\]|\\.)*'/g) || [])
        .map((s) => s.slice(1, -1))
        .join('')
        .replace(/\\'/g, "'")
        .replace(/\\\\/g, '\\');
      if (joined) keptBrief.set(url[1], joined);
    }

    const pub = /publisher:\s*'([^']+)'/.exec(block);
    if (pub) keptPublisher.set(url[1], pub[1]);
  });

  const posts = fetched.map((n) => {
    const url = n.blogUrl;
    return {
      title: normalise(n.title),
      url,
      date: n.publishedAt.slice(0, 10),
      readTime: n.readTimeInMinutes,
      cover: ((n.coverImage || {}).url || '').split('?')[0] || undefined,
      publisher: keptPublisher.get(url),
      brief: keptBrief.get(url) || normalise(n.brief).slice(0, 260),
    };
  });

  fs.writeFileSync(OUT, render(posts).replace(/\n/g, '\r\n'), 'utf8');

  const added = posts.filter((x) => !keptBrief.has(x.url));
  console.log(`Wrote ${posts.length} posts to ${path.relative(process.cwd(), OUT)}`);
  if (added.length) {
    console.log(`${added.length} new post(s); write a proper brief for:`);
    added.forEach((x) => console.log(`  - ${x.title}`));
  } else {
    console.log('No new posts. Existing briefs preserved.');
  }
};

main().catch((err) => {
  console.error(`Failed: ${err.message}`);
  process.exit(1);
});
